import type { Field, Module } from './modules';
import { today } from './types';

const text = (key: string, label: string, required = true): Field => ({
  key,
  label,
  required,
  maxLength: 200,
});
const num = (key: string, label: string, required = false, step = '1'): Field => ({
  key,
  label,
  required,
  type: 'number',
  min: 0,
  step,
  default: 0,
});
const date = (key: string, label: string, required = true): Field => ({
  key,
  label,
  type: 'date',
  required,
  default: today(),
});
const notes = (key: string, label: string, required = false): Field => ({
  key,
  label,
  type: 'textarea',
  required,
  nullable: !required,
});
const select = (key: string, label: string, options: string[], value?: string): Field => ({
  key,
  label,
  type: 'select',
  options,
  required: true,
  default: value || options[0],
});
const ref = (key: string, label: string, lookup: string, required = true): Field => ({
  key,
  label,
  type: 'select',
  lookup,
  required,
  nullable: !required,
});
const active: Field = { key: 'is_active', label: 'Actif', type: 'checkbox', default: true };
const employee = ref('employee_id', 'Collaborateur', 'erp/references/employees');
const comment = notes('comment', 'Motif / commentaire', true);
const paymentFields = [
  text('payment_reference', 'Référence de paiement'),
  date('paid_on', 'Date de paiement'),
];
const materials: Field = {
  key: 'materials',
  label: 'Matières et quantités',
  type: 'rows',
  required: true,
  fields: [
    ref('stock_item_id', 'Article matière', 'stock-items'),
    { ...num('quantity', 'Quantité à consommer', true, '0.0001'), min: 0.0001, default: 1 },
  ],
  hint: 'Nomenclature : quantité par unité produite. Ordre de production : quantité totale à consommer pour tout le lot.',
};
const col = (key: string, label: string, format?: Module['columns'][number]['format']) => ({
  key,
  label,
  format,
});
const status = col('status', 'Statut', 'status');
function resource(
  code: string,
  path: string,
  title: string,
  singular: string,
  permission: string,
  fields: Field[],
  columns: Module['columns'],
  editableStatuses: string[],
  description: string,
): Module {
  return {
    key: `erp/${code}`,
    path,
    title,
    singular,
    permission,
    fields: ['projects', 'production-orders', 'campaigns'].includes(code)
      ? [
          ...fields,
          {
            ...ref(
              'owner_id',
              'Responsable du dossier',
              `erp/references/assignees?module=${permission}`,
              false,
            ),
            nullable: false,
            createOnly: true,
            hint: 'Laisser vide pour vous-même. La direction peut attribuer le dossier au service concerné dès sa création.',
          },
        ]
      : fields,
    columns,
    editableStatuses,
    description,
    detail: true,
    createPermission: `${permission}.create`,
    ...(editableStatuses.length ? { updatePermission: `${permission}.update` } : {}),
  };
}
const action = (
  key: string,
  label: string,
  permission: string,
  statuses: string[],
  fields: Field[] = [],
  differentMaker = false,
) => ({ key, label, permission, statuses, fields, differentMaker });
